function getAllSingleLevelExams(){ return EXAMS.map(e => ({...e})); }
function getSingleLevelExam(trade, level){ return EXAMS.find(e => e.trade === trade && e.level === Number(level)) || null; }

// The project contains purchasable quizzes only for levels that can be
// prepared for as individual challenge levels. The next level is displayed as
// a technical-training information page and is never passed into Stripe.
function getTrainingRequiredLevels() {
  const grouped = new Map();

  EXAMS.forEach(exam => {
    if (!grouped.has(exam.trade)) {
      grouped.set(exam.trade, {
        trade: exam.trade,
        tradeTitle: exam.tradeTitle,
        challengeLevels: []
      });
    }
    grouped.get(exam.trade).challengeLevels.push(Number(exam.level));
  });

  return [...grouped.values()].map(item => {
    const challengeLevels = [...new Set(item.challengeLevels)].sort((a, b) => a - b);
    return {
      trade: item.trade,
      tradeTitle: item.tradeTitle,
      challengeLevels,
      trainingLevel: Math.max(...challengeLevels) + 1,
      infoUrl: `/trades/${item.trade}/level-${Math.max(...challengeLevels) + 1}-exam-questions`
    };
  });
}

module.exports = { getAllSingleLevelExams, getSingleLevelExam, getTrainingRequiredLevels };
