(function() {
  const questions = redSealPlumberInterprovincialSet3Questions;
  const STORAGE_KEY = "redSealPlumberSet2Progress";
  let activeQuestions = [];
  let currentIndex = 0;
  let userAnswers = [];
  let timer = null;
  let secondsLeft = 90;
  let lastMode = "all";

  const $ = (id) => document.getElementById(id);
  const escapeHtml = (value) => String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");

  function shuffleCopy(arr) {
    const copy = [...arr];
    for (let i = copy.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
  }

  function categories() {
    return ["All Questions", ...Array.from(new Set(questions.map(q => q.category)))];
  }

  function populateCategories() {
    const select = $("practiceCategory");
    select.innerHTML = categories().map(cat => `<option value="${escapeHtml(cat)}">${escapeHtml(cat)}</option>`).join("");
    $("totalQuestionsPill").textContent = `Questions: ${questions.length}`;
  }

  function getSelectedPool() {
    const selected = $("practiceCategory").value || "All Questions";
    return selected === "All Questions" ? questions : questions.filter(q => q.category === selected);
  }

  function saveProgress() {
    if (!activeQuestions.length) return;
    localStorage.setItem(STORAGE_KEY, JSON.stringify({
      activeIds: activeQuestions.map(q => q.id),
      currentIndex,
      userAnswers,
      lastMode,
      category: $("practiceCategory").value
    }));
    $("resumeQuizBtn").style.display = "inline-block";
  }

  function loadProgress() {
    try {
      const saved = JSON.parse(localStorage.getItem(STORAGE_KEY));
      if (!saved || !saved.activeIds) return false;
      activeQuestions = saved.activeIds.map(id => questions.find(q => q.id === id)).filter(Boolean);
      if (!activeQuestions.length) return false;
      currentIndex = saved.currentIndex || 0;
      userAnswers = saved.userAnswers || new Array(activeQuestions.length).fill(null);
      lastMode = saved.lastMode || "all";
      showQuiz();
      renderQuestion();
      startTimer();
      return true;
    } catch {
      return false;
    }
  }

  function startQuiz(pool) {
    const mode = $("quizMode").value;
    lastMode = mode;
    let selectedPool = pool || getSelectedPool();

    if (mode === "section") {
      const size = Math.max(1, parseInt($("sectionSize").value || "50", 10));
      selectedPool = shuffleCopy(selectedPool).slice(0, Math.min(size, selectedPool.length));
    }

    activeQuestions = selectedPool;
    currentIndex = 0;
    userAnswers = new Array(activeQuestions.length).fill(null);
    showQuiz();
    renderQuestion();
    startTimer();
    saveProgress();
  }

  function showQuiz() {
    $("setupSection").classList.add("hidden");
    $("oceanSection").classList.add("hidden");
    $("resultSection").classList.add("hidden");
    $("quizSection").classList.remove("hidden");
  }

  function startTimer() {
    clearInterval(timer);
    secondsLeft = 90;
    updateTimer();
    timer = setInterval(() => {
      secondsLeft -= 1;
      updateTimer();
      if (secondsLeft <= 0) {
        clearInterval(timer);
        if (currentIndex < activeQuestions.length - 1) {
          currentIndex++;
          renderQuestion();
          startTimer();
        } else {
          submitQuiz();
        }
      }
    }, 1000);
  }

  function updateTimer() {
    const minutes = String(Math.floor(secondsLeft / 60)).padStart(2, "0");
    const seconds = String(secondsLeft % 60).padStart(2, "0");
    $("timerBox").textContent = `${minutes}:${seconds}`;
  }

  function renderQuestion() {
    if (!activeQuestions.length) return;
    const q = activeQuestions[currentIndex];
    $("quizQuestionTitle").textContent = `Question ${currentIndex + 1} of ${activeQuestions.length}`;
    $("quizMeta").textContent = q.category;
    $("quizQuestionText").textContent = q.question;
    $("quizProgress").style.width = `${((currentIndex + 1) / activeQuestions.length) * 100}%`;
    $("hintBox").classList.add("hidden");
    $("hintText").textContent = q.explanation.split(".")[0] + ".";

    $("quizOptions").innerHTML = q.options.map((option, idx) => {
      const checked = userAnswers[currentIndex] === idx ? "checked" : "";
      return `
        <label class="option-card">
          <input type="radio" name="quizOption" value="${idx}" ${checked} />
          <span><strong>${String.fromCharCode(65 + idx)}.</strong> ${escapeHtml(option)}</span>
        </label>
      `;
    }).join("");

    document.querySelectorAll("input[name='quizOption']").forEach(input => {
      input.addEventListener("change", (e) => {
        userAnswers[currentIndex] = parseInt(e.target.value, 10);
        renderNavigator();
        saveProgress();
      });
    });

    $("prevBtn").disabled = currentIndex === 0;
    $("nextBtn").textContent = currentIndex === activeQuestions.length - 1 ? "Finish" : "Next";
    renderNavigator();
  }

  function renderNavigator() {
    $("navigator").innerHTML = activeQuestions.map((_, idx) => {
      const answered = userAnswers[idx] !== null && userAnswers[idx] !== undefined;
      const current = idx === currentIndex;
      const cls = current ? "nav-btn current" : answered ? "nav-btn answered" : "nav-btn";
      return `<button type="button" class="${cls}" data-index="${idx}">${idx + 1}</button>`;
    }).join("");

    document.querySelectorAll("#navigator button").forEach(btn => {
      btn.addEventListener("click", () => {
        currentIndex = parseInt(btn.dataset.index, 10);
        renderQuestion();
        startTimer();
        saveProgress();
      });
    });
  }

  function submitQuiz() {
    clearInterval(timer);
    const correct = activeQuestions.reduce((sum, q, idx) => sum + (userAnswers[idx] === q.answer ? 1 : 0), 0);
    const percentage = Math.round((correct / activeQuestions.length) * 100);
    $("quizSection").classList.add("hidden");
    $("resultSection").classList.remove("hidden");
    $("resultCategory").textContent = $("practiceCategory").value || "All Questions";
    $("resultScore").textContent = `${correct} / ${activeQuestions.length}`;
    $("resultPercentage").textContent = `${percentage}%`;
    $("resultPerformance").textContent = percentage >= 80 ? "Strong" : percentage >= 70 ? "Passing range" : "Needs review";
    $("passPrediction").textContent = percentage >= 70 ? "Likely pass with review" : "Keep practising";
    localStorage.removeItem(STORAGE_KEY);
    $("resumeQuizBtn").style.display = "none";
    renderReview("all");
  }

  function renderReview(filter) {
    let indexes = activeQuestions.map((_, idx) => idx);
    if (filter === "incorrect") indexes = indexes.filter(idx => userAnswers[idx] !== activeQuestions[idx].answer);
    if (filter === "unanswered") indexes = indexes.filter(idx => userAnswers[idx] === null || userAnswers[idx] === undefined);

    $("reviewSection").innerHTML = indexes.map(idx => {
      const q = activeQuestions[idx];
      const chosen = userAnswers[idx];
      const isCorrect = chosen === q.answer;
      return `
        <div class="card review-card">
          <div class="muted small">${escapeHtml(q.category)}</div>
          <h3>Question ${idx + 1}: ${escapeHtml(q.question)}</h3>
          <p><strong>Your answer:</strong> ${chosen === null || chosen === undefined ? "Unanswered" : escapeHtml(q.options[chosen])}</p>
          <p><strong>Correct answer:</strong> ${escapeHtml(q.options[q.answer])}</p>
          <p><strong>Result:</strong> ${isCorrect ? "Correct" : "Review"}</p>
          <p><strong>Explanation:</strong> ${escapeHtml(q.explanation)}</p>
        </div>
      `;
    }).join("") || `<div class="card"><p>No questions match this review filter.</p></div>`;
  }

  function renderOcean() {
    const term = ($("searchQuestions").value || "").toLowerCase();
    const pool = getSelectedPool().filter(q =>
      q.question.toLowerCase().includes(term) ||
      q.category.toLowerCase().includes(term) ||
      q.options.some(o => o.toLowerCase().includes(term))
    );

    $("oceanQuestionCount").textContent = `${pool.length} questions shown`;
    $("oceanQuestions").innerHTML = pool.map(q => `
      <div class="card review-card">
        <div class="muted small">${escapeHtml(q.category)}</div>
        <h3>${q.id}. ${escapeHtml(q.question)}</h3>
        <ol type="A">
          ${q.options.map(option => `<li>${escapeHtml(option)}</li>`).join("")}
        </ol>
        <p><strong>Answer:</strong> ${String.fromCharCode(65 + q.answer)} — ${escapeHtml(q.options[q.answer])}</p>
        <p><strong>Explanation:</strong> ${escapeHtml(q.explanation)}</p>
      </div>
    `).join("");
  }

  function startUnansweredOnly() {
    const saved = JSON.parse(localStorage.getItem("answeredHistory") || "{}");
    const pool = questions.filter(q => saved[q.id] === undefined);
    startQuiz(pool.length ? pool : questions);
  }

  function startIncorrectOnly() {
    const saved = JSON.parse(localStorage.getItem("answeredHistory") || "{}");
    const pool = questions.filter(q => saved[q.id] === false);
    startQuiz(pool.length ? pool : questions);
  }

  $("startQuizBtn").addEventListener("click", () => startQuiz());
  $("resumeQuizBtn").addEventListener("click", loadProgress);
  $("showOceanBtn").addEventListener("click", () => {
    $("oceanSection").classList.remove("hidden");
    renderOcean();
  });
  $("hideOceanBtn").addEventListener("click", () => $("oceanSection").classList.add("hidden"));
  $("searchQuestions").addEventListener("input", renderOcean);
  $("practiceCategory").addEventListener("change", renderOcean);
  $("prevBtn").addEventListener("click", () => {
    if (currentIndex > 0) {
      currentIndex--;
      renderQuestion();
      startTimer();
      saveProgress();
    }
  });
  $("nextBtn").addEventListener("click", () => {
    if (currentIndex < activeQuestions.length - 1) {
      currentIndex++;
      renderQuestion();
      startTimer();
      saveProgress();
    } else {
      submitQuiz();
    }
  });
  $("submitQuizBtn").addEventListener("click", submitQuiz);
  $("hintBtn").addEventListener("click", () => $("hintBox").classList.toggle("hidden"));
  $("restartSameBtn").addEventListener("click", () => startQuiz(getSelectedPool()));
  $("backSetupBtn").addEventListener("click", () => {
    clearInterval(timer);
    $("resultSection").classList.add("hidden");
    $("setupSection").classList.remove("hidden");
  });
  $("reviewAllBtn").addEventListener("click", () => renderReview("all"));
  $("reviewUnansweredBtn").addEventListener("click", () => renderReview("unanswered"));
  $("reviewIncorrectBtn").addEventListener("click", () => renderReview("incorrect"));
  $("unansweredOnlyBtn").addEventListener("click", startUnansweredOnly);
  $("incorrectOnlyBtn").addEventListener("click", startIncorrectOnly);

  populateCategories();
  if (localStorage.getItem(STORAGE_KEY)) $("resumeQuizBtn").style.display = "inline-block";
})();
